//! `jx export gradle`: a Kotlin-DSL build that mirrors the jx manifest and
//! lockfile.
//!
//! Like the Maven exporter, this is a conservative conversion: direct
//! dependencies carry the concrete versions recorded in `jx.lock`, dev
//! dependencies become `testImplementation`, classifiers keep their
//! `group:name:version:classifier` form, and `[overrides]` become dependency
//! constraints. Platform BOMs are not emitted (their effect is already in the
//! locked versions), and no plugin configuration is invented beyond the
//! `application`/`java-library` plugin, the Java toolchain and the JUnit
//! Platform.
//!
//! Repositories are deliberately fixed to `mavenCentral()`: jx's
//! `config.toml` (mirrors, extra repositories) belongs to the machine, not to
//! the project, so exporting it would write a private URL into the source
//! tree. The ADR records that limitation.

use std::fmt::Write as _;

use jx_common::error::{JxError, Kind};

/// One dependency in the exported Gradle build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GradleDependency {
    pub group_id: String,
    pub artifact_id: String,
    pub version: String,
    pub classifier: Option<String>,
    /// Test-only dependencies use `testImplementation`.
    pub test: bool,
}

impl GradleDependency {
    pub fn new(
        group_id: impl Into<String>,
        artifact_id: impl Into<String>,
        version: impl Into<String>,
    ) -> Self {
        GradleDependency {
            group_id: group_id.into(),
            artifact_id: artifact_id.into(),
            version: version.into(),
            classifier: None,
            test: false,
        }
    }

    pub fn classifier(mut self, classifier: impl Into<String>) -> Self {
        self.classifier = Some(classifier.into());
        self
    }

    pub fn test(mut self) -> Self {
        self.test = true;
        self
    }

    /// `group:name:version[:classifier]`, the notation Gradle accepts as a
    /// single string.
    pub fn notation(&self) -> String {
        match &self.classifier {
            Some(classifier) => format!(
                "{}:{}:{}:{}",
                self.group_id, self.artifact_id, self.version, classifier
            ),
            None => format!("{}:{}:{}", self.group_id, self.artifact_id, self.version),
        }
    }
}

/// Everything needed to render the Gradle build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GradleProject {
    pub group_id: String,
    pub artifact_id: String,
    pub version: String,
    pub java_release: u32,
    pub main_class: Option<String>,
    pub dependencies: Vec<GradleDependency>,
    /// Locked versions for `[overrides]`, emitted as dependency constraints.
    pub overrides: Vec<GradleDependency>,
}

/// The two files a Gradle build needs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GradleExport {
    /// `build.gradle.kts`
    pub build: String,
    /// `settings.gradle.kts`
    pub settings: String,
}

/// Render a deterministic Kotlin-DSL Gradle build.
pub fn export(project: &GradleProject) -> Result<GradleExport, JxError> {
    validate_ident("group", &project.group_id)?;
    validate_ident("project name", &project.artifact_id)?;
    validate_value("version", &project.version)?;
    if let Some(main) = &project.main_class {
        validate_value("mainClass", main)?;
    }
    for dependency in project.dependencies.iter().chain(&project.overrides) {
        validate_ident("dependency group", &dependency.group_id)?;
        validate_ident("dependency artifact", &dependency.artifact_id)?;
        validate_value("dependency version", &dependency.version)?;
        if let Some(classifier) = &dependency.classifier {
            validate_value("dependency classifier", classifier)?;
        }
    }

    let mut build = String::new();
    build.push_str(
        "// Generated by `jx export gradle` from project.toml and jx.lock.\n\
         // Plugin configuration, annotation processors and runtime images are\n\
         // not reproduced; review this build before relying on it.\n\n",
    );
    build.push_str("plugins {\n");
    build.push_str(if project.main_class.is_some() {
        "    application\n"
    } else {
        "    `java-library`\n"
    });
    build.push_str("}\n\n");

    let _ = writeln!(build, "group = {}", kotlin_string(&project.group_id));
    let _ = writeln!(build, "version = {}", kotlin_string(&project.version));
    build.push('\n');

    build.push_str("java {\n");
    build.push_str("    toolchain {\n");
    let _ = writeln!(
        build,
        "        languageVersion = JavaLanguageVersion.of({})",
        project.java_release
    );
    build.push_str("    }\n");
    build.push_str("}\n\n");

    build.push_str("repositories {\n");
    build.push_str("    mavenCentral()\n");
    build.push_str("}\n\n");

    if !project.dependencies.is_empty() || !project.overrides.is_empty() {
        build.push_str("dependencies {\n");
        for dependency in &project.dependencies {
            let configuration = if dependency.test {
                "testImplementation"
            } else {
                "implementation"
            };
            let _ = writeln!(
                build,
                "    {configuration}({})",
                kotlin_string(&dependency.notation())
            );
        }
        if !project.overrides.is_empty() {
            if !project.dependencies.is_empty() {
                build.push('\n');
            }
            build.push_str("    constraints {\n");
            for override_dep in &project.overrides {
                let _ = writeln!(
                    build,
                    "        implementation({})",
                    kotlin_string(&override_dep.notation())
                );
            }
            build.push_str("    }\n");
        }
        build.push_str("}\n\n");
    }

    if let Some(main) = &project.main_class {
        build.push_str("application {\n");
        let _ = writeln!(build, "    mainClass = {}", kotlin_string(main));
        build.push_str("}\n\n");
    }

    if project
        .dependencies
        .iter()
        .any(|dependency| dependency.test)
    {
        build.push_str("tasks.test {\n");
        build.push_str("    useJUnitPlatform()\n");
        build.push_str("}\n");
    }

    // Trim a trailing blank line so a file without a test block still ends
    // with exactly one newline.
    while build.ends_with("\n\n") {
        build.pop();
    }
    if !build.ends_with('\n') {
        build.push('\n');
    }

    let mut settings = String::new();
    let _ = writeln!(
        settings,
        "rootProject.name = {}",
        kotlin_string(&project.artifact_id)
    );

    Ok(GradleExport { build, settings })
}

/// Quote a value as a Kotlin string literal. `$` is escaped so a project
/// name can never turn into a template; control characters are rejected
/// earlier by [`validate_value`].
fn kotlin_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '$' => out.push_str("\\$"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

fn validate_ident(what: &str, value: &str) -> Result<(), JxError> {
    let safe = !value.is_empty()
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'));
    if safe {
        Ok(())
    } else {
        Err(JxError::new(
            Kind::Manifest,
            format!("{what} {value:?} is not a valid Gradle identifier"),
        )
        .hint("use letters, digits and `.`, `_`, `-`; pass --group-id to pick a group"))
    }
}

fn validate_value(what: &str, value: &str) -> Result<(), JxError> {
    if value.is_empty() || value.chars().any(char::is_control) {
        return Err(JxError::new(
            Kind::Manifest,
            format!("{what} {value:?} cannot be written to a Gradle build"),
        )
        .hint("remove control characters from project.toml"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app() -> GradleProject {
        GradleProject {
            group_id: "com.example".into(),
            artifact_id: "app".into(),
            version: "0.1.0".into(),
            java_release: 25,
            main_class: Some("app.App".into()),
            dependencies: vec![
                GradleDependency::new("com.google.guava", "guava", "33.4.8-jre"),
                GradleDependency::new("org.junit.jupiter", "junit-jupiter", "5.11.4").test(),
                GradleDependency::new("org.example", "native", "1.0").classifier("windows-x86_64"),
            ],
            overrides: vec![GradleDependency::new("org.slf4j", "slf4j-api", "2.0.16")],
        }
    }

    #[test]
    fn application_build_carries_coordinates_scopes_and_constraints() {
        let export = export(&app()).unwrap();
        let build = &export.build;
        assert!(build.contains("    application\n"));
        assert!(!build.contains("java-library"));
        assert!(build.contains("group = \"com.example\""));
        assert!(build.contains("version = \"0.1.0\""));
        assert!(build.contains("JavaLanguageVersion.of(25)"));
        assert!(build.contains("    mavenCentral()\n"));
        assert!(build.contains("implementation(\"com.google.guava:guava:33.4.8-jre\")"));
        assert!(build.contains("testImplementation(\"org.junit.jupiter:junit-jupiter:5.11.4\")"));
        assert!(build.contains("implementation(\"org.example:native:1.0:windows-x86_64\")"));
        assert!(build.contains("    constraints {\n"));
        assert!(build.contains("        implementation(\"org.slf4j:slf4j-api:2.0.16\")"));
        assert!(build.contains("application {\n    mainClass = \"app.App\"\n}"));
        assert!(build.contains("tasks.test {\n    useJUnitPlatform()\n}"));
        assert_eq!(build.matches("implementation(\"org.slf4j").count(), 1);
        assert_eq!(build.matches("com.google.guava:guava").count(), 1);
        assert!(build.ends_with("}\n"));
    }

    #[test]
    fn library_build_uses_java_library_and_has_no_application_block() {
        let mut project = app();
        project.main_class = None;
        project.dependencies.retain(|dependency| !dependency.test);
        project.overrides.clear();
        let build = export(&project).unwrap().build;
        assert!(build.contains("`java-library`"));
        assert!(!build.contains("    application\n"));
        assert!(!build.contains("application {"));
        assert!(!build.contains("mainClass"));
        assert!(!build.contains("tasks.test"));
        assert!(!build.contains("constraints {"));
    }

    #[test]
    fn an_empty_library_is_still_a_valid_build() {
        let project = GradleProject {
            group_id: "local.jx".into(),
            artifact_id: "lib".into(),
            version: "0.1.0".into(),
            java_release: 21,
            main_class: None,
            dependencies: Vec::new(),
            overrides: Vec::new(),
        };
        let export = export(&project).unwrap();
        assert!(!export.build.contains("dependencies {"));
        assert_eq!(export.settings, "rootProject.name = \"lib\"\n");
        assert!(export.build.ends_with("}\n"));
    }

    #[test]
    fn values_are_quoted_and_unrepresentable_identifiers_rejected() {
        let mut project = app();
        project.version = "1.0-$x".into();
        let build = export(&project).unwrap().build;
        assert!(build.contains("version = \"1.0-\\$x\""), "{build}");

        project.version = "1.0".into();
        project.group_id = "com/example".into();
        assert!(export(&project).is_err());
        project.group_id = "com.example".into();
        project.artifact_id = "app name".into();
        assert!(export(&project).is_err());
        project.artifact_id = "app".into();
        project.version = "1.0\n2.0".into();
        assert!(export(&project).is_err());
    }
}
